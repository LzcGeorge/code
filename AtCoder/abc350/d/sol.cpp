// 答案/构造 是从样例中推出来的，不是猜出来的
struct DSU {
    std::vector<int> f, siz;
    
    DSU() {}
    DSU(int n) {
        init(n);
    }
    
    void init(int n) {
        f.resize(n);
        std::iota(f.begin(), f.end(), 0);
        siz.assign(n, 1);
    }
    
    int find(int x) {
        while (x != f[x]) {
            x = f[x] = f[f[x]];
        }
        return x;
    }
    
    bool same(int x, int y) {
        return find(x) == find(y);
    }
    
    bool merge(int x, int y) {
        x = find(x);
        y = find(y);
        if (x == y) {
            return false;
        }
        siz[x] += siz[y];
        f[y] = x;
        return true;
    }
};

void solve()
{
    int n,m;
    cin >> n >> m;
    DSU dsu(n);
    for(int i = 0; i < m; i ++) {
        int a,b;
        cin >> a >> b;
        a --, b --;
        dsu.merge(a,b);
    }

    ll res = 0;
    for(int i = 0; i < n; i ++) {
        if(dsu.find(i) == i) {
            ll x = dsu.siz[i];
            res += 1ll*x*(x - 1)/2;
        }
    }
    cout << res - m ;
}

